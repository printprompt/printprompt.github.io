const LANGS = { it: "Italiano", en: "English", es: "Español" };
export let lang = "it";

function pick() {
  const saved = localStorage.getItem("pp_lang");
  if (saved && LANGS[saved]) return saved;
  for (const l of navigator.languages || [navigator.language || "it"]) {
    const c = String(l).slice(0, 2).toLowerCase();
    if (LANGS[c]) return c;
  }
  return "it";
}

function tr(text) {
  if (lang === "it") return null;
  const key = text.trim();
  const idx = lang === "en" ? 0 : 1;
  if (T[key]) return text.replace(key, T[key][idx]);
  for (const [re, out] of PATTERNS) if (re.test(key)) return text.replace(key, key.replace(re, out[idx]));
  return null;
}

/** Traduce testi, segnaposto e titoli dentro un nodo. */
export function translate(root) {
  if (lang === "it" || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    if (!n.data.trim() || n.parentElement?.closest("script,style,textarea,.bubble")) continue;
    const t = tr(n.data);
    if (t !== null) n.data = t;
  }
  if (root.querySelectorAll) {
    root.querySelectorAll("[placeholder],[title],[aria-label]").forEach((el) => {
      for (const a of ["placeholder", "title", "aria-label"]) {
        const v = el.getAttribute(a);
        const t = v && tr(v);
        if (t) el.setAttribute(a, t);
      }
    });
  }
}

/** Avvio: sceglie la lingua, mette il selettore nell'intestazione e traduce tutto quello che compare. */
export function initI18n() {
  lang = pick();
  document.documentElement.lang = lang;
  const sel = document.createElement("select");
  sel.id = "lang";
  sel.setAttribute("aria-label", "Lingua / Language / Idioma");
  sel.style.cssText = "border:0;background:var(--chip);border-radius:999px;padding:6px 8px;font-weight:600";
  for (const [k, v] of Object.entries(LANGS)) {
    const o = document.createElement("option");
    o.value = k; o.textContent = v; if (k === lang) o.selected = true;
    sel.appendChild(o);
  }
  sel.onchange = () => { localStorage.setItem("pp_lang", sel.value); location.reload(); };
  document.querySelector(".top nav")?.appendChild(sel);
  translate(document.body);
  new MutationObserver((muts) => {
    for (const m of muts) m.addedNodes.forEach((n) => {
      if (n.nodeType === 1) translate(n);
      else if (n.nodeType === 3) { const t = tr(n.data); if (t !== null) n.data = t; }
    });
  }).observe(document.body, { childList: true, subtree: true });
}
